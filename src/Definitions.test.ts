/** @module Runs the definitions vectors, which TypeScript and Rust share. */
import { Definitions } from 'flargs'
import vectors from '../test/vectors/definitions.json' with { type: 'json' }
import fileVectors from '../test/vectors/file.json' with { type: 'json' }

describe('parse', () => {
  for (const vector of vectors.parse)
    test(vector.name, () => {
      if ('error' in vector) {
        const error = (() => {
          try {
            Definitions.parse(vector.input)
          } catch (error) {
            return error
          }
        })()
        expect(error).toBeInstanceOf(Definitions.InvalidDeclarationError)
        expect((error as Definitions.InvalidDeclarationError).key).toBe(vector.error)
        return
      }
      expect(Definitions.parse(vector.input)).toEqual(vector.output)
    })

  test('error message', () => {
    expect(() =>
      Definitions.parse({ PRICING: { default: 'd', options: ['a', 'b'], type: 'select' } }),
    ).toThrowErrorMatchingInlineSnapshot(`
      [Definitions.InvalidDeclarationError: The default of PRICING is not one of its options.

      To resolve: Fix the declaration of PRICING in \`.env.flags\`, or in the store definition.]
    `)
  })
})

describe('check', () => {
  for (const vector of vectors.check)
    test(vector.name, () => {
      const definitions = Definitions.parse(vector.definitions)
      expect(
        Definitions.check(definitions, vector.env, {
          now: vector.now,
          prefix: 'prefix' in vector ? vector.prefix : undefined,
        }),
      ).toEqual(vector.issues)
    })
})

describe('infer', () => {
  for (const vector of vectors.infer)
    test(JSON.stringify(vector.raw), () => {
      expect(Definitions.infer(vector.raw)).toEqual(vector.value)
    })
})

describe('decode', () => {
  // A valid default for each type, so each vector declares its flag.
  const defaults = { boolean: false, json: null, number: 0, string: '' }

  for (const vector of vectors.decode)
    test(`${vector.type} ${JSON.stringify(vector.raw)}`, () => {
      const definition = Definitions.parse({
        flag: {
          default:
            vector.type === 'select'
              ? vector.options![0]
              : defaults[vector.type as keyof typeof defaults],
          ...(vector.options ? { options: vector.options } : {}),
          type: vector.type,
        },
      })['flag']!

      if ('error' in vector) {
        expect(() => Definitions.decode(definition, vector.raw, 'flag')).toThrow(
          Definitions.InvalidValueError,
        )
        return
      }
      expect(Definitions.decode(definition, vector.raw, 'flag')).toEqual(vector.value)
    })

  test('the error names the variable, not the value', () => {
    const definition = Definitions.parse({
      TOKEN: { default: 'a', options: ['a'], type: 'select' },
    })['TOKEN']!
    expect(() => Definitions.decode(definition, 'secret-value', 'TOKEN'))
      .toThrowErrorMatchingInlineSnapshot(`
        [Definitions.InvalidValueError: The value of TOKEN is not a select value of the flag.

        To resolve: Set TOKEN to a value of the flag, as its declaration in \`.env.flags\` describes.]
      `)
  })
})

describe('defines', () => {
  const definitions = Definitions.parse({
    BANNER: { build: true, default: false, public: true, type: 'boolean' },
    LIMITS: { build: true, default: { requests: 1 }, type: 'json' },
    NEW_CHECKOUT: { default: false, type: 'boolean' },
  })

  test('replaces build flags only, from env then the default', () => {
    expect(Definitions.defines(definitions, { env: { BANNER: 'true' } })).toMatchInlineSnapshot(`
      {
        "flags.BANNER": "true",
        "flags.LIMITS": "{"requests":1}",
      }
    `)
  })

  test('values take precedence over env', () => {
    expect(
      Definitions.defines(definitions, {
        env: { BANNER: 'true' },
        values: { BANNER: false },
      })['flags.BANNER'],
    ).toMatchInlineSnapshot(`"false"`)
  })
})

describe('generate', () => {
  const definitions = Definitions.parse({
    NEW_CHECKOUT: { default: false, public: true, type: 'boolean' },
    PRICING: { default: 'a', options: ['a', 'b'], type: 'select' },
  })

  test('public flags only', () => {
    expect(Definitions.generate(definitions, { visibility: 'public' })).toMatchInlineSnapshot(`
      "// Generated by flargs. Do not edit.

      export const definitions = {
        "NEW_CHECKOUT": {
          "build": false,
          "default": false,
          "public": true,
          "type": "boolean"
        }
      } as const

      declare module 'flargs' {
        interface Register {
          definitions: typeof definitions
        }
      }
      "
    `)
  })
})

describe('parseFile', () => {
  for (const vector of fileVectors.parseFile)
    test(vector.name, () => {
      if ('error' in vector) {
        const error = (() => {
          try {
            Definitions.parseFile(vector.text)
          } catch (error) {
            return error
          }
        })()
        expect(error).toBeInstanceOf(Definitions.InvalidDeclarationError)
        expect((error as Definitions.InvalidDeclarationError).key).toBe(vector.error)
        return
      }
      expect(Definitions.parseFile(vector.text)).toEqual(vector.output)
    })

  test('error message names the line', () => {
    expect(() => Definitions.parseFile('# @type {number}\nRETRIES=three\n'))
      .toThrowErrorMatchingInlineSnapshot(`
        [Definitions.InvalidDeclarationError: The default of RETRIES is not a number value (line 2).

        To resolve: Fix the declaration of RETRIES in \`.env.flags\`, or in the store definition.]
      `)
  })
})

describe('removeFromFile', () => {
  test('removes the comments, the variable, and one blank line', () => {
    const text =
      '# @type {boolean}\nA=false\n\n# Beta.\n# @type {boolean}\nBETA=false\n\n# @type {boolean}\nC=true\n'
    expect(Definitions.removeFromFile(text, 'BETA')).toMatchInlineSnapshot(`
      "# @type {boolean}
      A=false

      # @type {boolean}
      C=true
      "
    `)
  })
})
