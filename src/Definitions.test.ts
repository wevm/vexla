/** @module Runs the definitions vectors, which TypeScript and Rust share. */
import { Definitions } from 'flargs'
import vectors from '../test/vectors/definitions.json' with { type: 'json' }

describe('parse', () => {
  for (const vector of vectors.parse)
    test(vector.name, () => {
      if ('error' in vector) {
        const error = (() => {
          try {
            Definitions.parse(vector.input)
          } catch (error) {
            return error
          }
        })()
        expect(error).toBeInstanceOf(Definitions.InvalidDeclarationError)
        expect((error as Definitions.InvalidDeclarationError).key).toBe(vector.error)
        return
      }
      expect(Definitions.parse(vector.input)).toEqual(vector.output)
    })

  test('error message', () => {
    expect(() =>
      Definitions.parse({ pricing: { default: 'd', options: ['a', 'b'], type: 'select' } }),
    ).toThrowErrorMatchingInlineSnapshot(`
      [Definitions.InvalidDeclarationError: The default of pricing is not one of its options.

      To resolve: Fix the declaration of pricing in the flags file, as the JSON Schema describes.]
    `)
  })

  test('envPrefix', () => {
    const definitions = Definitions.parse(
      { newCheckout: { default: false, type: 'boolean' } },
      { envPrefix: 'APP_' },
    )
    expect(definitions['newCheckout']?.env).toMatchInlineSnapshot(`"APP_NEW_CHECKOUT"`)
  })
})

describe('envOf', () => {
  for (const [key, env] of vectors.envOf)
    test(`${key}`, () => {
      expect(Definitions.envOf(key!)).toBe(env)
    })
})

describe('keyOf', () => {
  for (const [env, key] of vectors.keyOf)
    test(`${env}`, () => {
      expect(Definitions.keyOf(env!)).toBe(key)
    })
})

describe('fromEnv', () => {
  for (const vector of vectors.fromEnv)
    test(vector.name, () => {
      expect(Definitions.fromEnv(vector.env)).toEqual(vector.output)
    })
})

describe('check', () => {
  for (const vector of vectors.check)
    test(vector.name, () => {
      const definitions = Definitions.parse(vector.definitions)
      expect(Definitions.check(definitions, vector.env, { now: vector.now })).toEqual(vector.issues)
    })
})

describe('decode', () => {
  // A valid default for each type, so each vector declares its flag.
  const defaults = { boolean: false, json: null, number: 0, string: '' }

  for (const vector of vectors.decode)
    test(`${vector.type} ${JSON.stringify(vector.raw)}`, () => {
      const definition = Definitions.parse({
        flag: {
          default:
            vector.type === 'select'
              ? vector.options![0]
              : defaults[vector.type as keyof typeof defaults],
          ...(vector.options ? { options: vector.options } : {}),
          type: vector.type,
        },
      })['flag']!

      if ('error' in vector) {
        expect(() => Definitions.decode(definition, vector.raw, 'flag')).toThrow(
          Definitions.InvalidValueError,
        )
        return
      }
      expect(Definitions.decode(definition, vector.raw, 'flag')).toEqual(vector.value)
    })

  test('the error names the variable, not the value', () => {
    const definition = Definitions.parse({
      token: { default: 'a', options: ['a'], type: 'select' },
    })['token']!
    expect(() => Definitions.decode(definition, 'secret-value', 'token'))
      .toThrowErrorMatchingInlineSnapshot(`
      [Definitions.InvalidValueError: The value for token (FEATURE_TOKEN) is not a select value of the flag.

      To resolve: Set FEATURE_TOKEN to a value of the flag, as its declaration in the flags file describes.]
    `)
  })
})

describe('defines', () => {
  const definitions = Definitions.parse({
    banner: { build: true, default: false, public: true, type: 'boolean' },
    limits: { build: true, default: { requests: 1 }, type: 'json' },
    newCheckout: { default: false, type: 'boolean' },
  })

  test('replaces build flags only, from env then the default', () => {
    expect(Definitions.defines(definitions, { env: { FEATURE_BANNER: 'true' } }))
      .toMatchInlineSnapshot(`
      {
        "flags.banner": "true",
        "flags.limits": "{"requests":1}",
      }
    `)
  })

  test('values take precedence over env', () => {
    expect(
      Definitions.defines(definitions, {
        env: { FEATURE_BANNER: 'true' },
        values: { banner: false },
      })['flags.banner'],
    ).toMatchInlineSnapshot(`"false"`)
  })
})

describe('generate', () => {
  const definitions = Definitions.parse({
    newCheckout: { default: false, public: true, type: 'boolean' },
    pricing: { default: 'a', options: ['a', 'b'], type: 'select' },
  })

  test('public flags only', () => {
    expect(Definitions.generate(definitions, { visibility: 'public' })).toMatchInlineSnapshot(`
      "// Generated by flargs. Do not edit.

      export const definitions = {
        "newCheckout": {
          "build": false,
          "default": false,
          "env": "FEATURE_NEW_CHECKOUT",
          "public": true,
          "type": "boolean"
        }
      } as const

      declare module 'flargs' {
        interface Register {
          definitions: typeof definitions
        }
      }
      "
    `)
  })
})
